/** 解析一个标识 → 注册表 key(先字面命中, 再别名, 未收录返回别名后原值由调用方判 fallback)。 */
export function resolveBrandKey(platform: string): string {
  if (!platform) return "generic";
  if (platform in BRAND_GLYPHS) return platform;
  return BRAND_ALIASES[platform] ?? platform;
}

/** 是否命中注册表/别名(false = 应回退色块)。 */
export function hasBrandGlyph(platform: string): boolean {
  const key = resolveBrandKey(platform);
  return key in BRAND_GLYPHS;
}

